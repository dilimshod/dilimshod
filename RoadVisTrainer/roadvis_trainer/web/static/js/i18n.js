export const DICT = { uz, ru, en };

let current = "uz";

export function getLang() { return current; }

export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : "uz";
  document.documentElement.setAttribute("lang", current);
  try { localStorage.setItem("rv.lang", current); } catch (e) { /* ignore */ }
}

export function initLang() {
  setLang(document.documentElement.getAttribute("lang") || "uz");
}

/** Translates ``key`` and fills ``{name}`` placeholders. Falls back to Uzbek, then to the key itself. */
export function t(key, vars) {
  let s = DICT[current][key] ?? DICT.uz[key] ?? key;
  if (vars && typeof s === "string") {
    s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
  }
  return s;
}

/** Event kind name; unknown kinds (newer apps) are shown as their raw value split into words. */
export function kindName(kind) {
  const key = "kind." + kind;
  const s = DICT[current][key] ?? DICT.uz[key];
  return s || String(kind).replace(/([a-z])([A-Z])/g, "$1 $2").replace(/^./, (c) => c.toUpperCase());
}
